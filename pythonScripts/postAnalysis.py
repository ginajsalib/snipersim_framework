def canonical_name(key, rank):
    return f"{key}__{rank}"


def resolve_config_columns(df):
    resolved = {}
    missing = []
    for key, template in CONFIG_DIMENSIONS.items():
        for rank in RANKS:
            expected = f"{template}_{rank}"
            actual = find_col(df, expected)
            if actual is None:
                missing.append(expected)
            else:
                resolved[(key, rank)] = actual
    if missing:
        raise ValueError(
            f"Could not resolve the following expected config columns "
            f"(tried case/separator-insensitive matching): {missing}\n"
            f"Available columns: {list(df.columns)}\n"
            f"Was this file generated by the updated find_top3_configs_by_ppw / "
            f"merge_train_with_top3 scripts?"
        )
    ppw_cols = {}
    for rank in RANKS:
        actual = find_col(df, f"PPW_{rank}")
        if actual is None:
            raise ValueError(f"Could not resolve PPW_{rank} column. Available: {list(df.columns)}")
        ppw_cols[rank] = actual
    return resolved, ppw_cols


def normalize_config(vals):
    try:
        l2_0, l2_1, l3, btb0, btb1, pf0, pf1 = vals
        return (float(l2_0), float(l2_1), float(l3), float(btb0), float(btb1),
                int(pf0), int(pf1))
    except (ValueError, TypeError):
        return None


