            l3_pct = l3_changes / (len(cost_df) - 1) * 100 if len(cost_df) > 1 else 0
            out(f"    L3 cache      | {TECH_PARAMS['E_gate_per_l3_kb_pJ']:.1f} pJ/KB  | {l3_pct:.1f}%")

