        total_reconfig = cost_df['reconfig_energy_pJ'].sum()
        avg_reconfig = cost_df[cost_df['reconfig_energy_pJ'] > 0]['reconfig_energy_pJ'].mean() if n_changes > 0 else 0

        out()
